import { createServer } from 'vite';
import { chromium } from 'playwright-core';
import { mkdir, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath, URL } from 'node:url';
import process from 'node:process';
import console from 'node:console';

const root = fileURLToPath(new URL('../../../', import.meta.url));
const output = path.join(tmpdir(), 'soflia-live-agenda-preview');
await mkdir(output, { recursive: true });
const server = await createServer({ configFile: path.join(root, 'test/manual/live-agenda/vite.config.mts'), cacheDir: path.join(output, 'vite-cache') });
await server.listen();
const browser = await chromium.launch({ executablePath: process.env.BROWSER_EXECUTABLE || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 960 }, timezoneId: 'America/Mexico_City' });
const errors = [];
const checks = [];
page.on('pageerror', error => errors.push(error.message));
await page.route('https://fonts.googleapis.com/**', route => route.abort());
const ready = () => page.waitForFunction(() => globalThis.document.querySelector('.agenda-results')?.getAttribute('aria-busy') === 'false');
const check = (name, passed) => { checks.push({ name, passed }); if (!passed) throw new Error(name); };
const capture = name => page.screenshot({ path: path.join(output, `${name}.png`), animations: 'disabled' });

try {
  await page.goto('http://127.0.0.1:4322/', { waitUntil: 'domcontentloaded' });
  await ready();
  await page.getByRole('button', { name: 'Organización', exact: true }).click();
  await ready();
  check('administración con agenda, historial y gestión', await page.getByRole('button', { name: 'Historial', exact: true }).count() === 1 && await page.getByRole('button', { name: 'Gestionar en Learning' }).count() === 1);
  await capture('agenda-claro');
  await page.getByRole('button', { name: 'Modo oscuro' }).click();
  await page.waitForTimeout(200);
  await capture('agenda-oscuro');
  await page.getByRole('button', { name: 'Historial', exact: true }).click();
  await page.getByText('Un punto de partida para tu proyecto', { exact: true }).waitFor();
  check('historial conserva estados reales y no ofrece entrada al aula', await page.getByText('Sin cierre registrado', { exact: true }).count() === 1 && await page.getByRole('button', { name: 'Unirme a la sesión' }).count() === 0);
  await capture('historial-oscuro');
  await page.getByRole('button', { name: 'Ver detalles: Un punto de partida para tu proyecto' }).click();
  check('detalles usan una ruta de Learning sin abrir medios', (await page.getByRole('status').textContent()).includes('https://learning.test/acme/live/'));
  await page.getByRole('combobox', { name: 'Perfil de ejemplo' }).selectOption('instructor');
  await ready();
  check('instructor recibe su navegación propia', await page.getByRole('button', { name: 'Clases que imparto' }).count() === 1);
  await page.getByRole('combobox', { name: 'Perfil de ejemplo' }).selectOption('platform_admin');
  await ready();
  check('etiqueta de administrador de plataforma', await page.getByText('Administración de plataforma', { exact: true }).count() === 1);
  await page.getByRole('combobox', { name: 'Perfil de ejemplo' }).selectOption('student');
  await ready();
  check('alumno solo tiene agenda próxima', await page.getByRole('button', { name: 'Historial', exact: true }).count() === 0 && await page.getByRole('button', { name: 'Gestionar en Learning' }).count() === 0 && await page.getByRole('button', { name: 'Clases que imparto' }).count() === 0);
  await page.getByRole('button', { name: 'Modo claro' }).click();
  await page.waitForTimeout(200);
  await capture('agenda-usuario');
  await page.setViewportSize({ width: 390, height: 844 });
  await capture('agenda-movil');
  check('sin desbordamiento horizontal a 390 px', await page.evaluate(() => globalThis.document.documentElement.scrollWidth <= globalThis.innerWidth && [...globalThis.document.querySelectorAll('.live-agenda')].every(element => element.scrollWidth <= element.clientWidth + 1)));
  await page.getByRole('combobox', { name: 'Estado de ejemplo' }).selectOption('empty');
  await page.getByText('Tu agenda está despejada', { exact: true }).waitFor();
  check('vacío explícito', await page.getByRole('alert').count() === 0);
  await page.getByRole('combobox', { name: 'Estado de ejemplo' }).selectOption('error');
  await page.getByRole('alert').waitFor();
  check('error recuperable distinto de vacío', await page.getByRole('button', { name: 'Reintentar' }).count() === 1 && await page.getByText('Tu agenda está despejada', { exact: true }).count() === 0);
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.getByRole('combobox', { name: 'Estado de ejemplo' }).selectOption('sessions');
  await ready();
  await page.getByRole('button', { name: 'Cerrar sesiones síncronas' }).focus();
  check('cierre accesible por teclado', await page.evaluate(() => globalThis.document.activeElement?.getAttribute('aria-label') === 'Cerrar sesiones síncronas'));
  check('sin errores del renderer', errors.length === 0);
  await writeFile(path.join(output, 'verification.json'), JSON.stringify({ checks, errors }, null, 2));
  console.log(JSON.stringify({ checks, output }, null, 2));
} finally {
  await browser.close();
  await server.close();
}
