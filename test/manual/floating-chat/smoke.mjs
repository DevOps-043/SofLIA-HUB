import { createServer } from 'vite';
import react from '@vitejs/plugin-react';
import { createRequire } from 'node:module';
import { mkdir, mkdtemp, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { resolve } from 'node:path';
import { _electron } from 'playwright-core';

const require=createRequire(import.meta.url),root=process.cwd();
const reports=resolve('openspec/changes/floating-soflia-chat/reports/compact-drag');
const server=await createServer({configFile:false,root,cacheDir:await mkdtemp(resolve(tmpdir(),'soflia-floating-qa-')),envDir:resolve(root,'test/manual/floating-chat'),plugins:[react()],optimizeDeps:{entries:['test/manual/floating-chat/index.html']},server:{host:'127.0.0.1',port:0}});
await server.listen();let app;
try {
  await mkdir(reports,{recursive:true});
  app=await _electron.launch({executablePath:require('electron'),args:[resolve(root,'test/manual/project-panel/electron.cjs')],env:{...process.env,PROJECT_PANEL_PREVIEW_URL:`http://127.0.0.1:${server.httpServer.address().port}/test/manual/floating-chat/index.html`}});
  const page=await app.firstWindow();page.setDefaultTimeout(20000);
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  const capture=async (name,bounds)=>{
    await page.evaluate(()=>document.fonts.ready);
    const rectangle=bounds ? {x:Math.floor(bounds.x),y:Math.floor(bounds.y),width:Math.ceil(bounds.width),height:Math.ceil(bounds.height)} : undefined;
    const png=await app.evaluate(async({BrowserWindow},rect)=>{const contents=BrowserWindow.getAllWindows()[0].webContents;await contents.capturePage(rect,{stayHidden:true,stayAwake:true});await new Promise(resolve=>setTimeout(resolve,120));return(await contents.capturePage(rect,{stayHidden:true,stayAwake:true})).toPNG().toString('base64');},rectangle);
    await writeFile(resolve(reports,name),Buffer.from(png,'base64'));
  };
  await page.getByRole('button',{name:'Abrir chat flotante con Soflia'}).click();
  const input=page.getByRole('textbox');await input.waitFor();
  const card=page.getByRole('region',{name:'Chat flotante con Soflia'}),dock=page.locator('.soflia-floating-dock');
  const initial=await card.boundingBox();
  if(initial.height>76||initial.width>381)throw new Error(`Barra demasiado grande: ${JSON.stringify(initial)}`);
  if(await input.evaluate(node=>document.activeElement===node))throw new Error('El campo tomó foco al abrir con ratón.');
  if(await card.getByText('Soflia Hub',{exact:true}).count())throw new Error('La cabecera todavía tiene marca.');
  await capture('barra-delgada-oscuro.png');
  await capture('barra-detalle.png',initial);
  const grip=page.getByRole('button',{name:'Mover chat flotante'}),start=await grip.boundingBox();
  await page.mouse.move(start.x+15,start.y+12);await page.mouse.down();
  await page.mouse.move(260,180,{steps:12});
  if(await dock.getAttribute('data-native-browser-overlay')!=='true')throw new Error('No se protegió la composición durante el arrastre.');
  await page.mouse.up();
  const moved=await card.boundingBox();
  if(moved.x>=initial.x-100||moved.y>=initial.y-100)throw new Error('El arrastre no cambió la posición.');
  if(await dock.getAttribute('data-native-browser-overlay'))throw new Error('Quedó bloqueada la composición tras soltar.');
  const nextGrip=await grip.boundingBox();await page.mouse.move(nextGrip.x+15,nextGrip.y+12);await page.mouse.down();
  await page.evaluate(()=>window.dispatchEvent(new Event('blur')));
  if(await dock.getAttribute('data-native-browser-overlay'))throw new Error('La pérdida de foco dejó el arrastre activo.');
  await page.mouse.up();
  await input.fill('Conserva este borrador al moverme');
  await page.getByRole('button',{name:'Minimizar chat flotante'}).click();
  await page.getByRole('button',{name:'Abrir chat flotante con Soflia'}).click();
  if(await input.inputValue()!=='Conserva este borrador al moverme')throw new Error('Se perdió el borrador.');
  const reopened=await card.boundingBox();if(Math.abs(reopened.x-moved.x)>1||Math.abs(reopened.y-moved.y)>1)throw new Error('Se perdió la posición.');
  await capture('chat-arrastrado.png');
  await page.getByRole('button',{name:'Modelo del chat flotante'}).click();await page.getByRole('menu',{name:'Modelos de Soflia'}).waitFor();await capture('modelos-compactos.png');
  await page.getByRole('menuitemradio').nth(1).click();
  await page.getByRole('button',{name:'Simular pérdida de selección'}).click();
  await page.getByRole('button',{name:'Preparar chat del proyecto para escribir'}).waitFor();
  const idle=await card.boundingBox();if(idle.height>76)throw new Error('El estado sin selección volvió a crecer.');
  await capture('reposo-sin-seleccion.png');
  await page.getByRole('button',{name:'Preparar chat del proyecto para escribir'}).click();await input.waitFor();
  const upperGrip=await grip.boundingBox();await page.mouse.move(upperGrip.x+15,upperGrip.y+12);await page.mouse.down();await page.mouse.move(260,30,{steps:8});await page.mouse.up();
  const upperHeader=await page.locator('.soflia-floating-header').boundingBox();
  const onTop=await page.evaluate(point=>!!document.elementFromPoint(point.x,point.y)?.closest('.soflia-floating-header'),{x:upperHeader.x+20,y:upperHeader.y+12});
  if(!onTop)throw new Error('La barra del navegador cubre el chat al arrastrarlo hacia arriba.');
  await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].setContentSize(420,360));
  await page.waitForFunction(()=>innerWidth===420);
  await input.fill('Mensaje de prueba local');await input.press('Enter');
  await page.waitForFunction(()=>{const rect=document.querySelector('.soflia-floating-card').getBoundingClientRect();return rect.right<=innerWidth&&rect.bottom<=innerHeight&&rect.top>=0;});
  await page.evaluate(()=>document.documentElement.classList.remove('dark'));await capture('barra-compacta-claro.png');
  if(errors.length)throw new Error(errors.join('\n'));
  console.log('QA Electron correcta: barra de 380 px y hasta 76 px de alto, sin marca ni autofocus con ratón, arrastre real, captura/liberación, posición/borrador conservados, modelos, reposo accionable y resize 420×360. Controlador simulado, sin proveedores ni WebContentsView real.');
} finally {await app?.close();await server.close();}
