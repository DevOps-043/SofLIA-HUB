const { chromium } = require('playwright-core');
const fs = require('node:fs');
const path = require('node:path');

(async () => {
  const output = path.resolve('openspec/changes/redesign-live-sessions/reports');
  fs.mkdirSync(output, { recursive: true });
  const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, timezoneId: 'America/Mexico_City' });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.goto('http://127.0.0.1:4320/');
  await page.getByRole('combobox', { name: 'Vista de ejemplo' }).selectOption('participant');
  await page.getByRole('button', { name: 'Volver a mis sesiones' }).click();
  await page.getByRole('button', { name: 'Unirme a la sesión' }).waitFor();
  await page.screenshot({ path: path.join(output, 'agenda-dark.png') });
  await page.getByRole('button', { name: 'Modo claro' }).click();
  await page.screenshot({ path: path.join(output, 'agenda-light.png') });
  await page.getByRole('button', { name: 'Modo oscuro' }).click();
  await page.getByLabel('Abrir menú de herramientas').click();
  if ((await page.getByRole('menuitem').allTextContents()).join('|') !== 'NavegadorCtrl+T|ReunionesCtrl+M|Sesiones síncronas') throw new Error('Orden del menú incorrecto');
  await page.getByRole('menuitem', { name: 'Sesiones síncronas' }).click();
  await page.getByRole('button', { name: 'Unirme a la sesión' }).click();
  const classroom = page.getByRole('region', { name: 'Aula SofLIA', exact: true });
  const canvas = page.getByRole('region', { name: 'Espacio de la sesión', exact: true });
  await canvas.waitFor();
  if (await canvas.innerText() || await classroom.getByRole('button').count() !== 2 || await classroom.getByRole('textbox').count()) throw new Error('El aula debe quedar vacía con solo volver y cerrar');
  await page.screenshot({ path: path.join(output, 'aula-empty-dark.png') });
  await page.getByRole('button', { name: 'Modo claro' }).click();
  await page.screenshot({ path: path.join(output, 'aula-empty-light.png') });
  await page.getByRole('button', { name: 'Modo oscuro' }).click();
  await page.getByLabel('Volver a mis sesiones').click();
  await page.getByRole('button', { name: 'Unirme a la sesión' }).click();
  await page.getByLabel('Cerrar aula').click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Unirme a la sesión' }).waitFor();
  await page.screenshot({ path: path.join(output, 'agenda-mobile.png') });
  await page.getByRole('button', { name: 'Unirme a la sesión' }).click();
  await canvas.waitFor();
  await page.screenshot({ path: path.join(output, 'aula-empty-mobile.png') });
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth || [...document.querySelectorAll('.learning-workspace')].some((element) => element.scrollWidth > element.clientWidth + 1));
  if (overflow || errors.length) throw new Error(JSON.stringify({ overflow, errors }));
  console.log(JSON.stringify({ success: true, screenshots: 6, flow: 'agenda → aula vacía → ambos temas → volver → cerrar → ancho reducido', errors }));
  await browser.close();
})().catch((error) => { console.error(error); process.exit(1); });
